      userId: json['user_id'],
      companyId: json['company_id'],
      unitId: json['unit_id'],
      firstName: json['first_name'],
      lastName: json['last_name'],
      gender: json['gender'],
      dob: json['dob'],
      mobile: json['mobile'],
      email: json['email'],
      imagePath: json['image_path'],
      comingFrom: json['coming_from'],
      city: json['city'],
      state: json['state'],
      country: json['country'],
      visitorType: json['visitor_type'],
      idProof: json['id_proof'],
      idProofType: json['id_proof_type'],
      idProofImage: json['id_proof_image'],
      idProofImagePath: json['id_proof_img_path'],
      passSerialNo: json['pass_serial_no'],
      visitorCode: json['code'],
      passType: json['pass_type'],
      passStartDate: json['pass_start_date'],
      passEndDate: json['pass_end_date'],
