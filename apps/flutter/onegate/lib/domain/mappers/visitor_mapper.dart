      'company_id': entity.companyId,
      'unit_id': entity.unitId,
      'first_name': entity.firstName,
      'last_name': entity.lastName,
      'gender': entity.gender,
      'dob': entity.dob,
      'mobile': entity.mobile,
      'email': entity.email,
      'image_path': entity.imagePath,
      'coming_from': entity.comingFrom,
      'city': entity.city,
      'state': entity.state,
      'country': entity.country,
      'visitor_type': entity.visitorType,
      'id_proof': entity.idProof,
      'id_proof_type': entity.idProofType,
      'id_proof_image': entity.idProofImage,
      'id_proof_img_path': entity.idProofImagePath,
      'pass_serial_no': entity.passSerialNo,
      'code': entity.visitorCode,
      'pass_type': entity.passType,
      'pass_start_date': entity.passStartDate,
      'pass_end_date': entity.passEndDate,
      'pass_validity': entity.passValidity,
      'card_no': entity.cardNo,
      'status': entity.status,
      'category': entity.category,
      'is_log_visible': entity.isLogVisible,
      'created_by': entity.createdBy,
      'created_at': entity.createdAt,
      'updated_by': entity.updatedBy,
      'updated_at': entity.updatedAt,
      'purpose': entity.purpose,
